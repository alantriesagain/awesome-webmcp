// The built-in JS plugins compiled into widecode: plugins/<id>/index.ts (type-checked against
// widecode.d.ts with the rest of the repository) with their types stripped by node, as the string
// constants of src/runtime/builtin.ts (generated; written only when it changes). A plugin
// file ends with `export {};` so TypeScript checks it as a module; that line is dropped here. The
// plugin guide (PLUGINS.md) and the API's types (widecode.d.ts) go the same way into
// src/runtime/docs.ts, for the harness plugin's api tool: the installed binary has no repository.
// The build's version (git describe of the workspace, else the package's version) and time go into
// src/runtime/build-info.ts, so a running binary says which build it is.
//
// For a test run (light-native's LIGHT_NATIVE_COMMAND is "test") the three modules are written so
// their text stays the same while plugins, the docs and the clock change: builtin.ts names the
// plugins and reads their stripped code from src/runtime/generated/ when the program starts,
// docs.ts reads PLUGINS.md and widecode.d.ts, and build-info.ts says "test". scriptc's cache keys a
// program by its text, so a plugin's change or a minute passing compiles no test again.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { join } from "node:path";

const forTest = process.env.LIGHT_NATIVE_COMMAND === "test";
/** Write `text` to `path` only when it changes, so its time moves only then. */
const keep = (path, text) => {
  if (!existsSync(path) || readFileSync(path, "utf8") !== text) writeFileSync(path, text);
};
const dir = "plugins";
const out = "src/runtime/builtin.ts";
/** The built-in plugins by id: a folder's index.ts (plugins/<id>/index.ts), or a file of its own (plugins/<id>.ts). */
const files = (existsSync(dir) ? readdirSync(dir).sort() : [])
  .map((f) => (f.endsWith(".ts") ? { id: f.slice(0, -3), path: join(dir, f) } : existsSync(join(dir, f, "index.ts")) ? { id: f, path: join(dir, f, "index.ts") } : null))
  .filter((f) => f !== null);
/** The languages plugin's list, from the package's one table. */
const languagesOf = (code) => {
  const table = readFileSync("node_modules/@lightstart/highlight/languages.ts", "utf8");
  const re = /new LanguageEntry\("([^"]+)", (\[[^\]]*\]), (\[[^\]]*\])\)/g;
  const lines = [];
  for (let m = re.exec(table); m !== null; m = re.exec(table)) lines.push("  { id: " + JSON.stringify(m[1]) + ", extensions: " + m[2] + ", fences: " + m[3] + ", tokenizer: " + JSON.stringify(m[1]) + " },");
  return code.replace(/const LANGUAGES(?:: [^=]+)? = \[\n[\s\S]*?\n\];/, "const LANGUAGES = [\n" + lines.join("\n") + "\n];");
};
const generated = "src/runtime/generated";
const plugins = files.map((f) => {
  let source = readFileSync(f.path, "utf8");
  if (f.id === "languages") source = languagesOf(source);
  return { name: f.id + ".js", code: stripTypeScriptTypes(source).replace(/^export \{\};\s*$/m, "") };
});
let text;
if (forTest) {
  mkdirSync(generated, { recursive: true });
  // .txt, so the type check does not take them for the program's JavaScript.
  for (const p of plugins) keep(join(generated, p.name + ".txt"), p.code);
  text =
    "// Generated by scripts/builtin-plugins.mjs (run from the app) for a test run: the plugins' code is read from\n" +
    "// " + generated + "/ when the program starts, so this text stays the same while they change.\n" +
    'import { readTextOr } from "@lightstart/lib/fs.ts";\n' +
    'import { PluginSource } from "@lightstart/plugins/sources.ts";\n\n' +
    "const NAMES: string[] = [" + plugins.map((p) => JSON.stringify(p.name)).join(", ") + "];\n\n" +
    "const load = (): PluginSource[] => {\n" +
    "  const out: PluginSource[] = [];\n" +
    '  for (const name of NAMES) out.push(new PluginSource("builtin:" + name, readTextOr(' + JSON.stringify(generated + "/") + " + name + \".txt\", \"\")));\n" +
    "  return out;\n" +
    "};\n\n" +
    "/** The built-in JS plugins, read from the app's folder. */\n" +
    "export const BUILTIN_PLUGINS: PluginSource[] = load();\n";
} else {
  const entries = plugins.map((p) => "  new PluginSource(" + JSON.stringify("builtin:" + p.name) + ", " + JSON.stringify(p.code) + "),");
  text =
    "// Generated by scripts/builtin-plugins.mjs (run from the app) from plugins/<id>/index.ts: edit those, not this.\n" +
    'import { PluginSource } from "@lightstart/plugins/sources.ts";\n\n' +
    "/** The built-in JS plugins, in the binary. */\n" +
    "export const BUILTIN_PLUGINS: PluginSource[] = [\n" +
    entries.join("\n") +
    (entries.length > 0 ? "\n" : "") +
    "];\n";
}
keep(out, text);

const docsOut = "src/runtime/docs.ts";
const docs = forTest
  ? "// Generated by scripts/builtin-plugins.mjs (run from the app) for a test run: the files are read when the program starts.\n" +
    'import { readTextOr } from "@lightstart/lib/fs.ts";\n\n' +
    "/** The plugin guide (PLUGINS.md), read from the app's folder. */\n" +
    'export const PLUGIN_GUIDE: string = readTextOr("PLUGINS.md", "");\n\n' +
    "/** The plugin API's types (widecode.d.ts). */\n" +
    'export const PLUGIN_TYPES: string = readTextOr("widecode.d.ts", "");\n'
  : "// Generated by scripts/builtin-plugins.mjs (run from the app) from PLUGINS.md and widecode.d.ts: edit those, not this.\n\n" +
  "/** The plugin guide (PLUGINS.md), as the binary carries it for the harness plugin's api tool. */\n" +
  "export const PLUGIN_GUIDE: string = " + JSON.stringify(readFileSync("PLUGINS.md", "utf8")) + ";\n\n" +
  "/** The plugin API's types (widecode.d.ts). */\n" +
  "export const PLUGIN_TYPES: string = " + JSON.stringify(readFileSync("widecode.d.ts", "utf8")) + ";\n";
keep(docsOut, docs);

const versionOf = () => {
  try {
    return execFileSync("git", ["describe", "--always", "--dirty", "--tags"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return String(JSON.parse(readFileSync("package.json", "utf8")).version ?? "0");
  }
};
const infoOut = "src/runtime/build-info.ts";
const info =
  "// Generated by scripts/builtin-plugins.mjs (run from the app) at build time: edit nothing here.\n\n" +
  "/** The build: the workspace's git describe (a tag, the commits past it, the commit, -dirty), else the package's version. */\n" +
  "export const BUILD_VERSION: string = " + JSON.stringify(forTest ? "test" : versionOf()) + ";\n\n" +
  "/** When it was built (ISO, to the minute). */\n" +
  "export const BUILD_TIME: string = " + JSON.stringify(forTest ? "test" : new Date().toISOString().slice(0, 16) + "Z") + ";\n";
keep(infoOut, info);
