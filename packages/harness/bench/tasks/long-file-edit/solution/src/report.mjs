const pad2 = (value) => String(value).padStart(2, "0");
const round1 = (value) => Math.round(value * 10) / 10;

/** The metric with `id`, or null. */
export const metricFor = (id) => {
  for (const metric of metrics) {
    if (metric.id === id) return metric;
  }
  return null;
};

/** The label of the metric with `id`, or the id itself. */
export const metricLabel = (id) => {
  const metric = metricFor(id);
  return metric === null ? id : metric.label;
};

/** Every metric id, in the order the catalog lists them. */
export const metricIds = () => metrics.map((metric) => metric.id);

/** The ids owned by `owner`. */
export const metricIdsFor = (owner) => metrics.filter((metric) => metric.owner === owner).map((metric) => metric.id);

/** `value` for `metric`, cut to its precision and given its unit. */
export const formatMetric = (metric, value) => {
  const factor = Math.pow(10, metric.precision);
  const shown = Math.round(value * factor) / factor;
  return String(shown) + " " + metric.unit;
};

/** The gauge text for `value`, always between 0 and 100. */
export const gaugeText = (value) => {
  const capped = Math.min(100, Math.max(0, value));
  return round1(capped) + "%";
};

/** The progress text for `value`, always between 0 and 100. */
export const progressText = (value) => {
  const capped = Math.min(100, Math.max(0, value));
  return Math.round(capped) + "%";
};

/** The score badge text for `value`, between 0 and 120 because scores carry bonus points. */
export const badgeText = (value) => {
  const capped = Math.min(120, Math.max(0, value));
  return round1(capped) + "%";
};

/** A dashboard line for `metric` at `value`, with its gauge. */
export const dashboardLine = (metric, value) => {
  const ratio = metric.range[1] === metric.range[0] ? 0 : ((value - metric.range[0]) / (metric.range[1] - metric.range[0])) * 100;
  return pad2(metricIds().indexOf(metric.id)) + " " + metric.label + ": " + formatMetric(metric, value) + " [" + gaugeText(ratio) + "]";
};
