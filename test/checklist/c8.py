from common import *
d = repo()
app = App(d, OUT + "c8.log", LIVE, cols=200, rows=50)
app.type('Use the Bash tool to run exactly: python3 -c "import time; time.sleep(30)" and then say finished.')
app.key("enter")
s = app.wait_screen(lambda s: "⏺ Bash python3" in s, 60)
time.sleep(1)
mark = len(app.text_log())
t0 = time.time()
app.key("esc")
idle(app, mark, 20)
print("interrupt took %.1f s" % (time.time() - t0))
time.sleep(0.3)
show("after Esc", app.screen())
mark = len(app.text_log())
app.type("Launch two Agent subagents in parallel in one message (subagent_type general-purpose, not in the background): one reads README.md and reports its first line, the other reads list.txt and reports its line count. Then tell me both answers.")
app.key("enter")
idle(app, mark, 180); time.sleep(0.5)
s = app.screen()
show("parallel subagents", s)
pos = App.find(s, "⏺ Agent")
if pos:
    app.press(pos[0] + 2, pos[1])
    s = app.screen()
    show("first card opened by a press", s)
app.close()
