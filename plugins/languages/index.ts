// The languages colored in the code column and in the chat's code blocks: JavaScript (and JSON),
// TypeScript, CSS, HTML (with the JavaScript and CSS inside it) and Markdown (with its fenced code
// in the fence's language), each with the file extensions and fence names it answers to and the
// core tokenizer that colors it. Switched off, nothing is colored. Another file type colored like
// one of these is one more entry here, or a plugin of its own.

interface Language {
  id: string;
  extensions: string[];
  fences: string[];
  tokenizer: string;
}

const LANGUAGES: Language[] = [
  // @languages generated by scripts/builtin-plugins.mjs from @lightstart/highlight's languages.ts
];

lightcode.plugin({
  id: "languages",
  activate(api) {
    for (const l of LANGUAGES) api.languages.add(l);
  },
});

export {};
