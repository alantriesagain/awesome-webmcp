from common import *
def leftovers():
    r = subprocess.run(["pgrep", "-f", "--", "--no-session-persistence"], capture_output=True, text=True)
    return [p for p in r.stdout.split() if p.strip()]
plain = repo(git=False)
a = repo()
print("== 11: a folder outside git")
app = App(plain, OUT + "c11.log", LIVE, cols=200, rows=40)
s = app.screen()
print("tree:", [l[100:131].strip() for l in s.split("\n")[1:6]])
print("status:", s.split("\n")[-1][:60])
mark = len(app.text_log())
app.type("Use the Edit tool to change 'two' to 'TWO' in list.txt, then say done."); app.key("enter")
idle(app, mark); time.sleep(1)
s = app.screen()
print("code followed:", [l[132:175].rstrip() for l in s.split("\n")[1:5]])
print("== 12: /open while idle, then while running")
app.type("/open " + a); app.key("enter"); time.sleep(1)
s = app.screen()
print("after /open (idle):", s.split("\n")[1][100:131].strip(), "| branch shown:", "main" in s.split("\n")[-1])
app.type('Use the Bash tool to run exactly: python3 -c "import time; time.sleep(30)" and then say finished.'); app.key("enter")
app.wait_screen(lambda s: "⏺ Bash python3" in s, 60)
print("CLI processes while running:", len(leftovers()))
app.type("/open " + plain); app.key("enter"); time.sleep(0.5)
print("first /open while running:", app.screen().split("\n")[-1][-75:].strip())
app.type("/open " + plain); app.key("enter"); time.sleep(1.5)
s = app.screen()
print("second /open switched:", "list.txt" in s and "main" not in s.split("\n")[-1], "| CLI processes left:", len(leftovers()))
print("== 13: quit mid-turn")
app.type('Use the Bash tool to run exactly: python3 -c "import time; time.sleep(30)" and then say finished.'); app.key("enter")
app.wait_screen(lambda s: "⏺ Bash python3" in s, 60)
print("CLI processes while running:", len(leftovers()))
app.key("ctrl-c"); time.sleep(0.3); app.key("ctrl-c")
time.sleep(1.5)
print("app still running:", app.running(), "| CLI processes left:", len(leftovers()))
app.close()
