// A text preview of the Peers tab (30 cells) and its details page (80 cells), over two daemons on the loopback; not a test.
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createWidecode } from "../src/compose.ts";
import { Conversation } from "@widecode/conversation/conversation.ts";
import { JsPanel } from "../src/runtime/views.ts";
import { DaemonOptions, startDaemon } from "@widecode/peers";
import { TRoot, mount, unmount } from "@lightstart/light/native/tui";
import { openWorkspace } from "@light/workspace/workspace.ts";
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const root = mkdtempSync(join(tmpdir(), "widecode-peers-preview-"));
const storeA = join(root, "a"), storeB = join(root, "b"), repo = join(root, "repo"), repoB = join(root, "repo-b");
mkdirSync(storeA); mkdirSync(storeB); mkdirSync(repo);
process.env.WIDECODE_HOME = storeA;
const sh = (c) => spawnSync("sh", ["-c", c], { encoding: "utf8" });
sh(`git init -q -b main ${repo} && echo one > ${repo}/a.txt && git -C ${repo} add . && git -C ${repo} -c user.email=t@t -c user.name=t commit -qm first`);
sh(`git clone -q ${repo} ${repoB} && echo two > ${repoB}/b.txt && git -C ${repoB} add . && git -C ${repoB} -c user.email=t@t -c user.name=t commit -qm "second, elsewhere"`);
const oa = new DaemonOptions(); oa.port = 0; oa.bind = "127.0.0.1"; oa.name = "alanleal-730QDA"; oa.discovery = false; oa.syncMs = 0;
const ob = new DaemonOptions(); ob.port = 0; ob.bind = "127.0.0.1"; ob.name = "Alans-MacBook-Pro"; ob.discovery = false; ob.syncMs = 0;
const a = await startDaemon(storeA, oa); const b = await startDaemon(storeB, ob);
await b.share(repoB, "", "live", null, null); await b.host("mirror", "");
const ws = await openWorkspace(repo, 100);
const app = createWidecode(ws, new Conversation(ws.folder), null);
mount(app.shell, new TRoot()); app.shell.resize(200); await app.host.load();
const tab = app.host.screen.findPanel("peers");
const rows = (w) => { const out = []; for (let i = 0; i < tab.rows.count(); i++) out.push(tab.rows.line(i, w).runs.map((r) => r.text).join("")); return out; };
app.host.screen.focus("side"); app.host.screen.showPanel("peers");
for (let i = 0; i < 100 && !rows(30).some((r) => r.includes("share this folder")); i++) await wait(20);
app.host.kernel.commands.run("/peers share");
for (let i = 0; i < 100 && !rows(30).some((r) => r.includes("◆ repo")); i++) await wait(20);
app.host.kernel.commands.run("/peers host mirror");
app.host.kernel.commands.run("/peers pair");
for (let i = 0; i < 100 && a.offer === null; i++) await wait(20);
await b.pairJoin("127.0.0.1", a.port, a.offer.code, Date.now());
app.host.kernel.commands.run("/peers pair");
app.shell.handleKey(new (await import("@lightstart/light/native/tui")).KeyEvent("char", "r", false, false, false));
for (let i = 0; i < 300 && !rows(30).some((r) => r.includes("↓1")); i++) await wait(20);
const frame = (title, lines, w) => { console.log("┌─ " + title + " " + "─".repeat(Math.max(0, w - title.length - 3)) + "┐"); for (const l of lines) console.log("│" + l.padEnd(w, " ").slice(0, w) + "│"); console.log("└" + "─".repeat(w) + "┘"); };
frame("Peers (30 cells)", [tab.info().map((r) => r.text).join("")].concat(rows(30)), 30);
const pageRows = (w) => { const src = app.code.pane.view.source; if (src === null || typeof src.line !== "function") return ["(no plugin view shown: " + String(src && src.constructor && src.constructor.name) + ")"]; const out = []; for (let i = 0; i < src.count(); i++) out.push(src.line(i, w).runs.map((r) => r.text).join("")); return out; };
tab.press(rows(30).findIndex((r) => r.includes("alanleal-730QDA")), 4); await wait(200);
frame("This machine (80 cells)", pageRows(80), 80);
tab.press(rows(30).findIndex((r) => r.includes("● Alans")), 4); await wait(300);
frame("Peer (80 cells)", pageRows(80), 80);
tab.press(rows(30).findIndex((r) => r.includes("◆ repo-b")), 4); await wait(300);
frame("Repository (80 cells)", pageRows(80), 80);
unmount(app.shell); ws.close(); a.stop(); b.stop(); rmSync(root, { recursive: true, force: true });
