// The built-in JS plugins compiled into widecode: plugins/*.ts (type-checked against
// widecode.d.ts with the rest of the repository) with their types stripped by node, as the string
// constants of src/runtime/builtin.ts (generated; written only when it changes). A plugin
// file ends with `export {};` so TypeScript checks it as a module; that line is dropped here. The
// plugin guide (PLUGINS.md) and the API's types (widecode.d.ts) go the same way into
// src/runtime/docs.ts, for the harness plugin's api tool: the installed binary has no repository.
// The build's version (git describe of the workspace, else the package's version) and time go into
// src/runtime/build-info.ts, so a running binary says which build it is.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { join } from "node:path";

const dir = "plugins";
const out = "src/runtime/builtin.ts";
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".ts")).sort() : [];
/** The languages plugin's list, from the package's one table. */
const languagesOf = (code) => {
  const table = readFileSync("node_modules/@light/highlight/languages.ts", "utf8");
  const re = /new LanguageEntry\("([^"]+)", (\[[^\]]*\]), (\[[^\]]*\])\)/g;
  const lines = [];
  for (let m = re.exec(table); m !== null; m = re.exec(table)) lines.push("  { id: " + JSON.stringify(m[1]) + ", extensions: " + m[2] + ", fences: " + m[3] + ", tokenizer: " + JSON.stringify(m[1]) + " },");
  return code.replace(/const LANGUAGES(?:: [^=]+)? = \[\n[\s\S]*?\n\];/, "const LANGUAGES = [\n" + lines.join("\n") + "\n];");
};
const entries = files.map((f) => {
  let source = readFileSync(join(dir, f), "utf8");
  if (f === "languages.ts") source = languagesOf(source);
  const code = stripTypeScriptTypes(source).replace(/^export \{\};\s*$/m, "");
  return "  new PluginSource(" + JSON.stringify("builtin:" + f.replace(/\.ts$/, ".js")) + ", " + JSON.stringify(code) + "),";
});
const text =
  "// Generated by scripts/builtin-plugins.mjs (run from the app) from plugins/*.ts: edit those, not this.\n" +
  'import { PluginSource } from "@light/plugins/sources.ts";\n\n' +
  "/** The built-in JS plugins, in the binary. */\n" +
  "export const BUILTIN_PLUGINS: PluginSource[] = [\n" +
  entries.join("\n") +
  (entries.length > 0 ? "\n" : "") +
  "];\n";
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);

const docsOut = "src/runtime/docs.ts";
const docs =
  "// Generated by scripts/builtin-plugins.mjs (run from the app) from PLUGINS.md and widecode.d.ts: edit those, not this.\n\n" +
  "/** The plugin guide (PLUGINS.md), as the binary carries it for the harness plugin's api tool. */\n" +
  "export const PLUGIN_GUIDE: string = " + JSON.stringify(readFileSync("PLUGINS.md", "utf8")) + ";\n\n" +
  "/** The plugin API's types (widecode.d.ts). */\n" +
  "export const PLUGIN_TYPES: string = " + JSON.stringify(readFileSync("widecode.d.ts", "utf8")) + ";\n";
if (!existsSync(docsOut) || readFileSync(docsOut, "utf8") !== docs) writeFileSync(docsOut, docs);

const versionOf = () => {
  try {
    return execFileSync("git", ["describe", "--always", "--dirty", "--tags"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return String(JSON.parse(readFileSync("package.json", "utf8")).version ?? "0");
  }
};
const infoOut = "src/runtime/build-info.ts";
const info =
  "// Generated by scripts/builtin-plugins.mjs (run from the app) at build time: edit nothing here.\n\n" +
  "/** The build: the workspace's git describe (a tag, the commits past it, the commit, -dirty), else the package's version. */\n" +
  "export const BUILD_VERSION: string = " + JSON.stringify(versionOf()) + ";\n\n" +
  "/** When it was built (ISO, to the minute). */\n" +
  "export const BUILD_TIME: string = " + JSON.stringify(new Date().toISOString().slice(0, 16) + "Z") + ";\n";
if (!existsSync(infoOut) || readFileSync(infoOut, "utf8") !== info) writeFileSync(infoOut, info);
